DO $m9r9_ownership_test$
DECLARE
  v_idea_id uuid := pg_catalog.current_setting('test.m9r9_idea_id')::uuid;
  v_result jsonb;
  v_count integer;
BEGIN
  SELECT pg_catalog.count(*) INTO v_count
    FROM public.idea_stages AS stage
    WHERE stage.idea_id = v_idea_id;
  IF v_count <> 0 THEN
    RAISE EXCEPTION 'Another participant read stage progress';
  END IF;
  v_result := public.request_idea_stage_confirmation(v_idea_id, 1::smallint);
  IF v_result->>'outcome' <> 'not_found_or_not_owned' THEN
    RAISE EXCEPTION 'Another participant changed stage state: %', v_result;
  END IF;
  v_result := public.set_idea_current_step(v_idea_id, 1::smallint);
  IF v_result->>'outcome' <> 'not_found_or_not_owned' THEN
    RAISE EXCEPTION 'Another participant changed the active stage: %', v_result;
  END IF;
END
$m9r9_ownership_test$;

