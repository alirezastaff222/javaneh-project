SELECT pg_catalog.set_config(
  'request.jwt.claim.sub', 'a9900000-0000-4000-8000-000000000001', true
);

DO $m9r9_progression_test$
DECLARE
  v_result jsonb;
  v_idea_id uuid;
  v_revision integer;
  v_stage smallint;
  v_expected_keys text[] := ARRAY[
    'define_problem',
    'identify_social_capacities',
    'develop_ideas',
    'implementation_plan',
    'feasibility_resilience',
    'idea_dossier',
    'human_review'
  ];
BEGIN
  v_result := public.create_idea('a9910000-0000-4000-8000-000000000001');
  IF v_result->>'outcome' <> 'created' THEN
    RAISE EXCEPTION 'Idea fixture creation failed: %', v_result;
  END IF;
  v_idea_id := (v_result->>'idea_id')::uuid;
  PERFORM pg_catalog.set_config(
    'test.m9r9_idea_id', v_idea_id::text, true
  );

  IF EXISTS (
    SELECT 1
      FROM public.idea_stages AS stage
      WHERE stage.idea_id = v_idea_id
        AND stage.stage_key <> v_expected_keys[stage.stage_number]
  ) OR (
    SELECT pg_catalog.count(*)
      FROM public.idea_stages AS stage
      WHERE stage.idea_id = v_idea_id
  ) <> 7 THEN
    RAISE EXCEPTION 'Canonical stage keys or order are incorrect';
  END IF;
  IF (
    SELECT stage.status
      FROM public.idea_stages AS stage
      WHERE stage.idea_id = v_idea_id AND stage.stage_number = 1
  ) <> 'in_progress'
     OR (
       SELECT pg_catalog.count(*)
         FROM public.idea_stages AS stage
         WHERE stage.idea_id = v_idea_id AND stage.status = 'locked'
     ) <> 6
     OR (
       SELECT idea.current_step
         FROM public.ideas AS idea
         WHERE idea.id = v_idea_id
     ) <> 1 THEN
    RAISE EXCEPTION 'New idea did not initialize at participant Stage 1';
  END IF;

  v_result := public.request_idea_stage_confirmation(v_idea_id, 2::smallint);
  IF v_result->>'outcome' <> 'invalid_state' THEN
    RAISE EXCEPTION 'A locked stage accepted a confirmation request: %', v_result;
  END IF;
  v_result := public.confirm_idea_stage(v_idea_id, 2::smallint, 1);
  IF v_result->>'outcome' <> 'invalid_state' THEN
    RAISE EXCEPTION 'A locked stage accepted confirmation: %', v_result;
  END IF;
  v_result := public.set_idea_current_step(v_idea_id, 2::smallint);
  IF v_result->>'outcome' <> 'invalid_state' THEN
    RAISE EXCEPTION 'A locked stage accepted navigation: %', v_result;
  END IF;

  v_result := public.save_idea_content(
    v_idea_id, 'a9920000-0000-4000-8000-000000000001', 1,
    '[{"stage_number":1,"data":{"content":"first saved draft"}}]'::jsonb
  );
  IF v_result->>'outcome' <> 'applied' THEN
    RAISE EXCEPTION 'Initial stage save failed: %', v_result;
  END IF;
  v_revision := (v_result->>'result_revision')::integer;
  v_result := public.save_idea_content(
    v_idea_id, 'a9920000-0000-4000-8000-000000000002', v_revision,
    '[{"stage_number":1,"data":{"content":"latest saved draft"}}]'::jsonb
  );
  IF v_result->>'outcome' <> 'applied' THEN
    RAISE EXCEPTION 'Ordinary draft save failed: %', v_result;
  END IF;
  v_revision := (v_result->>'result_revision')::integer;

  v_result := public.request_idea_stage_confirmation(v_idea_id, 1::smallint);
  IF v_result->>'outcome' <> 'requested' THEN
    RAISE EXCEPTION 'Stage 1 confirmation request failed: %', v_result;
  END IF;
  v_result := public.confirm_idea_stage(v_idea_id, 1::smallint, v_revision - 1);
  IF v_result->>'outcome' <> 'stale_revision'
     OR (
       SELECT stage.status
         FROM public.idea_stages AS stage
         WHERE stage.idea_id = v_idea_id AND stage.stage_number = 2
     ) <> 'locked' THEN
    RAISE EXCEPTION 'Failed confirmation unlocked the next stage: %', v_result;
  END IF;
  v_result := public.confirm_idea_stage(v_idea_id, 1::smallint, v_revision);
  IF v_result->>'outcome' <> 'confirmed'
     OR v_result->>'current_step' <> '2'
     OR (
       SELECT idea.current_step
         FROM public.ideas AS idea
         WHERE idea.id = v_idea_id
     ) <> 2
     OR (
       SELECT stage.status
         FROM public.idea_stages AS stage
         WHERE stage.idea_id = v_idea_id AND stage.stage_number = 2
     ) <> 'in_progress'
     OR (
       SELECT stage.status
         FROM public.idea_stages AS stage
         WHERE stage.idea_id = v_idea_id AND stage.stage_number = 3
     ) <> 'locked' THEN
    RAISE EXCEPTION 'Confirmation did not unlock exactly the next stage: %',
      v_result;
  END IF;

  v_result := public.confirm_idea_stage(v_idea_id, 1::smallint, v_revision);
  IF v_result->>'outcome' <> 'already_confirmed'
     OR v_result->>'current_step' <> '2' THEN
    RAISE EXCEPTION 'Repeated confirmation was not idempotent: %', v_result;
  END IF;
  v_result := public.request_idea_stage_confirmation(v_idea_id, 2::smallint);
  IF v_result->>'outcome' <> 'requested' THEN
    RAISE EXCEPTION 'Unlocked Stage 2 confirmation request failed: %', v_result;
  END IF;
  v_result := public.confirm_idea_stage(v_idea_id, 2::smallint, v_revision);
  IF v_result->>'outcome' <> 'confirmed'
     OR v_result->>'current_step' <> '3'
     OR (
       SELECT stage.status
         FROM public.idea_stages AS stage
         WHERE stage.idea_id = v_idea_id AND stage.stage_number = 3
     ) <> 'in_progress' THEN
    RAISE EXCEPTION 'Stage 2 did not persist progression: %', v_result;
  END IF;

  v_result := public.set_idea_current_step(v_idea_id, 1::smallint);
  IF v_result->>'outcome' <> 'saved' THEN
    RAISE EXCEPTION 'Revisiting a confirmed stage was rejected: %', v_result;
  END IF;
  FOR v_stage IN 3..6 LOOP
    v_result := public.request_idea_stage_confirmation(
      v_idea_id, v_stage::smallint
    );
    IF v_result->>'outcome' <> 'requested' THEN
      RAISE EXCEPTION 'Stage % request failed after prior confirmations: %',
        v_stage, v_result;
    END IF;
    v_result := public.confirm_idea_stage(
      v_idea_id, v_stage::smallint, v_revision
    );
    IF v_result->>'outcome' <> 'confirmed' THEN
      RAISE EXCEPTION 'Stage % confirmation failed: %', v_stage, v_result;
    END IF;
  END LOOP;

  IF (
    SELECT stage.status
      FROM public.idea_stages AS stage
      WHERE stage.idea_id = v_idea_id AND stage.stage_number = 7
  ) <> 'locked'
     OR (
       SELECT stage.data
         FROM public.idea_stages AS stage
         WHERE stage.idea_id = v_idea_id AND stage.stage_number = 7
     ) <> '{}'::jsonb THEN
    RAISE EXCEPTION 'Stage 7 became participant-editable';
  END IF;
  v_result := public.request_idea_stage_confirmation(v_idea_id, 7::smallint);
  IF v_result->>'outcome' <> 'invalid_input' THEN
    RAISE EXCEPTION 'Participant requested Stage 7 confirmation: %', v_result;
  END IF;
  v_result := public.save_idea_content(
    v_idea_id, 'a9920000-0000-4000-8000-000000000003', v_revision,
    '[{"stage_number":7,"data":{"content":"participant edit"}}]'::jsonb
  );
  IF v_result->>'outcome' <> 'invalid_state' THEN
    RAISE EXCEPTION 'Participant edited the human-review stage: %', v_result;
  END IF;

  v_result := public.submit_idea(
    v_idea_id, 'a9930000-0000-4000-8000-000000000001', v_revision
  );
  IF v_result->>'outcome' <> 'submitted'
     OR v_result->>'current_step' <> '7'
     OR (
       SELECT idea.current_step
         FROM public.ideas AS idea
         WHERE idea.id = v_idea_id
     ) <> 7 THEN
    RAISE EXCEPTION 'Submission did not transition to human review: %',
      v_result;
  END IF;
  v_result := public.submit_idea(
    v_idea_id, 'a9930000-0000-4000-8000-000000000001', v_revision
  );
  IF v_result->>'outcome' <> 'replayed'
     OR v_result->>'current_step' <> '7' THEN
    RAISE EXCEPTION 'Submission retry did not retain the human-review state: %',
      v_result;
  END IF;
  v_result := public.save_idea_content(
    v_idea_id, 'a9920000-0000-4000-8000-000000000003', v_revision,
    '[{"stage_number":6,"data":{"content":"submitted edit"}}]'::jsonb
  );
  IF v_result->>'outcome' <> 'invalid_state' THEN
    RAISE EXCEPTION 'Submitted dossier was editable through stage save: %',
      v_result;
  END IF;
END
$m9r9_progression_test$;

