DO $m9r9_schema_test$
BEGIN
  IF (
    SELECT c.is_generated <> 'ALWAYS'
      FROM information_schema.columns AS c
      WHERE c.table_schema = 'public'
        AND c.table_name = 'idea_stages'
        AND c.column_name = 'stage_key'
  ) IS DISTINCT FROM false THEN
    RAISE EXCEPTION 'Canonical stage keys are not generated by the database';
  END IF;
  IF pg_catalog.has_table_privilege(
    'authenticated', 'public.idea_stages', 'UPDATE'
  ) THEN
    RAISE EXCEPTION 'Participants can directly alter persistent stage state';
  END IF;
END
